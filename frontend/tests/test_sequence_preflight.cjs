const assert=require('node:assert/strict');
const {inspectQueue:inspect}=require('../point-sampling.js');
const units=Array.from({length:25},(_,i)=>['h'+i,'w'+i]);
assert.throws(()=>inspect(units,null,20),/最多需要24次/);
const ready=inspect(units,null,24);assert.equal(ready.upper,24);assert.equal(ready.freeSeed,true);
const state={status:'ready',submitted_ids:['h0','w0'],unassigned_ids:[],ambiguities:[],tracks:{F1:{history:[{candidate_id:'h0'}]}},calls:1,max_calls:30};
assert.equal(inspect(units,state,24).upper,24);
const partial={...state,submitted_ids:['h0']};assert.equal(inspect(units,partial,25).units[0].length,2);
assert.throws(()=>inspect(units,{...state,max_calls:10},24),/会话预算不足/);
assert.throws(()=>inspect([],null,20),/先选择/);
for(const bad of [NaN,-1,2.5,10001])assert.throws(()=>inspect(units,null,bad),/整数/);
assert.equal(inspect(Array.from({length:483},(_,i)=>['h'+i,'w'+i]),null,493,{mode:'batch-snapshot-v1',batchSize:50}).upper,493);
assert.equal(inspect(Array.from({length:483},(_,i)=>['h'+i,'w'+i]),null,513,{mode:'batch-snapshot-v1',batchSize:50,retryBudget:20}).upper,513);
assert.throws(()=>inspect(Array.from({length:483},(_,i)=>['h'+i,'w'+i]),null,493,{mode:'batch-snapshot-v1',batchSize:50,retryBudget:20}),/513/);
assert.equal(inspect([units[0]],null,0).upper,0);
assert.throws(()=>inspect(units,{...state,active_sequential_run:'x'},24),/未结束/);
const unresolved={...state,submitted_ids:[],tracks:{},unassigned_ids:['h0']};
assert.equal(inspect(units,unresolved,25).freeSeed,false);
console.log('sequence preflight: passed (budget, seed, remaining cap, partial group, invalid values)');
