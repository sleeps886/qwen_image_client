// Requires a local smoke server exposing /api/test-fake-gateway; never use a paid gateway.
async (page) => {
  const origin=new URL(page.url()).origin;
  const gatewayMarker=await page.request.get(origin+'/api/test-fake-gateway');
  if(!gatewayMarker.ok()||!(await gatewayMarker.json()).fake_gateway)throw new Error('Stop: fake model test server required');
  const assert=(value,message)=>{if(!value)throw new Error(message);};
  await page.waitForFunction(()=>!document.getElementById('example').disabled);
  await page.locator('#predictionAdvanced').evaluate(el=>el.hidden=false); await page.locator('#predictionDebug').evaluate(el=>el.open=true);
  await page.locator('#example').click();
  await page.locator('#predictionAdvanced').evaluate(el=>el.hidden=true);
  await page.locator('#chatOptions').evaluate(el=>el.open=true);
  await page.locator('#singlePrediction').uncheck();
  const fixture={candidates:Array.from({length:16},(_,i)=>({candidate_id:`P${i}`,t:i*10,bearing_deg:30+i*1.5,array:'hull',platform_id:'A'}))};
  fixture.candidates.push({candidate_id:'Q5',t:50,bearing_deg:60,array:'hull',platform_id:'A'});
  await page.locator('#datasetFile').setInputFiles({name:'chat-points.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(fixture))});
  let draft=JSON.parse(await page.locator('#chatInput').inputValue());
  assert(draft.point_data.history.length===3,'seed points not preloaded');
  assert(!JSON.stringify(draft).includes('P15'),'future batch leaked to composer');
  await page.locator('#questionTemplateMode').selectOption('auto');
  assert(!/[{}\[\]]/.test(await page.locator('#chatQuestion').inputValue()),'raw JSON shown in chat');
  assert((await page.locator('#pointDetailFields').textContent()).includes('方位角'),'Chinese property menu missing');
  assert(!(await page.locator('#pointDetailFields').textContent()).includes('航速'),'absent speed field shown');
  assert(!(await page.locator('#pointDetailFields').textContent()).includes('待估计'),'empty field placeholder shown');
  assert((await page.locator('#questionTemplateStage').textContent()).includes('初始化'),'initial template missing');
  await page.locator('#chatSend').click();
  assert((await page.locator('#chatNotice').textContent()).includes('费用'),'missing consent gate');
  await page.locator('#chatConsent').check();
  await page.locator('#chatPayload').evaluate(el=>el.open=true);
  const tampered=structuredClone(draft);tampered.point_data.history[0].bearing_deg=179;
  await page.locator('#chatInput').evaluate((el,text)=>el.value=text,JSON.stringify(tampered));await page.locator('#chatSend').click();
  assert((await page.locator('#chatNotice').textContent()).includes('不可直接改写'),'point editing not blocked');
  draft.question='请解释依据并预测下一段';await page.locator('#chatQuestion').fill(draft.question);
  await page.locator('#chatSend').click();
  await page.waitForFunction(()=>document.querySelectorAll('#chatMessages .assistant').length===1 && !document.getElementById('chatSend').disabled);
  assert((await page.locator('#chatMessages .user').textContent()).includes(draft.question),'user question missing');
  assert((await page.locator('#chatMessages .assistant').textContent()).includes('模拟网关回复'),'assistant result missing');
  draft=JSON.parse(await page.locator('#chatInput').inputValue());
  assert(draft.point_data.step_id===2,'next round not preloaded');
  assert(draft.point_data.new_candidates[0].candidate_id==='P5','wrong next candidate');
  assert(!JSON.stringify(draft).includes('P6'),'future candidate leaked');
  assert((await page.locator('#questionTemplateStage').textContent()).includes('连续预测'),'template not advanced');
  assert((await page.locator('#chatPointTable').textContent()).includes('Q5'),'synchronous group table missing Q5');
  assert(await page.locator('#chatPointTable input:checked').count()===1,'next time group was not selected');
  draft.question='新增点支持之前的判断吗？';await page.locator('#chatQuestion').fill(draft.question);
  await page.locator('#chatSend').click();
  await page.waitForFunction(()=>document.querySelectorAll('#chatMessages .assistant').length===2 && !document.getElementById('chatSend').disabled);
  assert((await page.locator('#chatMessages .assistant').last().textContent()).includes('P5'),'model did not use composer-selected time group');
  assert(await page.locator('#predictionChart polyline[stroke-dasharray]').count()===2,'chart predictions missing');
  await page.reload();
  await page.waitForFunction(()=>document.querySelectorAll('#chatMessages .assistant').length===2 && !document.getElementById('chatPrepare').disabled);
  assert(!await page.locator('#chatConsent').isChecked(),'chat consent restored');
  draft=JSON.parse(await page.locator('#chatInput').inputValue());
  assert(draft.point_data.step_id===3,'restored next-round data wrong');
  return {preloaded:true,questionAnswerRounds:2,tableSelectionUsed:true,chineseProperties:true,autoStageTemplate:true,consentGate:true,pointTamperBlocked:true,noFutureLeak:true,refreshRestored:true,realModelCalls:0};
}
